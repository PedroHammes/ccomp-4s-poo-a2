    private boolean validarDados(){
        if (txtNome.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Informe o nome.", "Erro", JOptionPane.ERROR_MESSAGE);
            return false;
        }

        if (txtCPF.getText().length() != 11){
            JOptionPane.showMessageDialog(this, "O CPF deve ter 11 dígitos.", "Erro", JOptionPane.ERROR_MESSAGE);
            return false;
        }

        try {
            Long.parseLong(txtCPF.getText());
        } catch (NumberFormatException e){
            JOptionPane.showMessageDialog(this, "O CPF deve conter apenas números.", "Erro", JOptionPane.ERROR_MESSAGE);
            return false;
        }

        int codigoAtual = -1;
        if (operacao.equals("editar")){
            codigoAtual = Integer.parseInt(txtCodigo.getText());
        }

        for (Aluno a : BancoDados.alunos) {
            if (a.getCpf().equals(txtCPF.getText()) && a.getCodigo() != codigoAtual) {
                JOptionPane.showMessageDialog(this, "CPF já cadastrado.", "Erro", JOptionPane.ERROR_MESSAGE);
                return false;
            }
        }

        if (cmbPlano.getSelectedIndex() == -1){
            JOptionPane.showMessageDialog(this, "Selecione um plano.", "Erro", JOptionPane.ERROR_MESSAGE);
            return false;
        }
        return true;
    }

    private void inserirRegistroTabela(Aluno a){
        DefaultTableModel modelo = (DefaultTableModel) tblAlunos.getModel();
        modelo.addRow(new Object[]{a.getCodigo(), a.getNome(), a.getCpf(), a.getTelefone(), a.getPlano(), a.isMensalidadeEmDia()});
    }

    private void carregarDados(){
        int linha = tblAlunos.getSelectedRow();

        String c = String.valueOf(tblAlunos.getValueAt(linha, 0));
        String n = String.valueOf(tblAlunos.getValueAt(linha, 1));
        String cpf = String.valueOf(tblAlunos.getValueAt(linha, 2));
        String t = String.valueOf(tblAlunos.getValueAt(linha, 3));
        Plano p = (Plano) tblAlunos.getValueAt(linha, 4);
        boolean emDia = (boolean) tblAlunos.getValueAt(linha, 5);

        txtCodigo.setText(c);
        txtNome.setText(n);
        txtCPF.setText(cpf);
        txtTelefone.setText(t);
        cmbPlano.setSelectedItem(p);
        chkEmDia.setSelected(emDia);
    }

    private void limparCampos(){
        txtCodigo.setText("");
        txtNome.setText("");
        txtCPF.setText("");
        txtTelefone.setText("");
        cmbPlano.setSelectedIndex(-1);
        txtMensalidade.setText("");
        chkEmDia.setSelected(false);
    }

    private void carregarPlanos(){
        for (Plano p : BancoDados.planos) {
            cmbPlano.addItem(p);
        }
    }

    private void carregarTabela(){
        for (Aluno a : BancoDados.alunos) {
            inserirRegistroTabela(a);
        }
    }

